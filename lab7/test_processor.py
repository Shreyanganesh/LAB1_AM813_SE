"""
Fuzz tests for processor.py using Hypothesis and pytest.

Each of the three functions is tested with random/invalid/edge-case inputs
generated by Hypothesis to discover crashes and unhandled exceptions.
"""

from hypothesis import given, strategies as st, settings
from processor import format_player_name, parse_frame, parse_scoreboard


# ──────────────────────────────────────────────────────────────
# Tests for format_player_name
# ──────────────────────────────────────────────────────────────

@given(st.text() | st.none())
@settings(max_examples=200)
def test_format_player_name_no_crash(s):
    """format_player_name must never crash on any input."""
    try:
        result = format_player_name(s)
    except Exception as e:
        assert False, f"format_player_name crashed on input {s!r}: {e}"


@given(st.text(min_size=1, alphabet=st.characters(whitelist_categories=("L",))))
def test_format_player_name_length_limit(s):
    """Result must never exceed 10 characters."""
    result = format_player_name(s)
    assert len(result) <= 10, f"Result '{result}' exceeds 10 chars"


@given(st.text(min_size=1, alphabet=st.characters(whitelist_categories=("L",))))
def test_format_player_name_title_case(s):
    """Result should be title-cased."""
    result = format_player_name(s)
    assert result == result.title(), f"'{result}' is not title-cased"


# ──────────────────────────────────────────────────────────────
# Tests for parse_frame
# ──────────────────────────────────────────────────────────────

@given(st.text() | st.none())
@settings(max_examples=200)
def test_parse_frame_no_crash(s):
    """parse_frame must never crash on any input."""
    try:
        result = parse_frame(s)
    except Exception as e:
        assert False, f"parse_frame crashed on input {s!r}: {e}"


@given(st.from_regex(r"^[0-9][0-9]$", fullmatch=True))
def test_parse_frame_two_digits_sum(s):
    """For two-digit frames, both values must be non-negative ints."""
    first, second = parse_frame(s)
    assert isinstance(first, int) and isinstance(second, int)
    assert first >= 0 and second >= 0


@given(st.integers(min_value=0, max_value=9))
def test_parse_frame_spare(n):
    """Spare notation n/ must return (n, 10-n)."""
    frame = f"{n}/"
    first, second = parse_frame(frame)
    assert first == n
    assert second == 10 - n
    assert first + second == 10


def test_parse_frame_strike():
    """Strike 'X' must return (10, 0)."""
    assert parse_frame("X") == (10, 0)
    assert parse_frame("x") == (10, 0)
    assert parse_frame(" X ") == (10, 0)


@given(st.just(""))
def test_parse_frame_empty_string(s):
    """Empty string should not crash."""
    try:
        parse_frame(s)
    except Exception as e:
        assert False, f"parse_frame crashed on empty string: {e}"


