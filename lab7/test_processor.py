@given(st.just(""))
def test_parse_scoreboard_empty_string(s):
    """Empty string should not crash."""
    try:
        result = parse_scoreboard(s)
    except Exception as e:
        assert False, f"parse_scoreboard crashed on empty string: {e}"


@given(
    st.lists(
        st.tuples(
            st.text(min_size=1, alphabet=st.characters(whitelist_categories=("L",))),
            st.integers(min_value=0, max_value=300),
        ),
        min_size=1,
        max_size=5,
    )
)
def test_parse_scoreboard_valid_round_trip(entries):
    """Valid 'Name:Score,...' input must parse correctly."""
    text = ",".join(f"{name}:{score}" for name, score in entries)
    result = parse_scoreboard(text)
    assert isinstance(result, dict)
    for name, score in entries:
        assert name.strip() in result


def test_parse_scoreboard_known_input():
    """Known input must produce correct dict."""
    result = parse_scoreboard("Asha:150,Ravi:132")
    assert result == {"Asha": 150, "Ravi": 132}
